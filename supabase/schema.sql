-- One time db script

create table if not exists public.articles (
  id bigint generated by default as identity primary key,
  title text not null,
  category text not null,
  author text default 'MLN Desk',
  summary text not null,
  content text not null,
  image_url text,
  lead boolean not null default false,
  featured boolean not null default false,
  created_at timestamptz not null default now()
);

create index if not exists articles_created_at_idx on public.articles (created_at desc);
create index if not exists articles_category_idx on public.articles (category);


alter table public.articles enable row level security;

drop policy if exists "Public read access" on public.articles;
create policy "Public read access"
  on public.articles
  for select
  to anon, authenticated
  using (true);

-- Articles are authored exclusively through the admin dashboard
-- (http://localhost:3000/admin). No seed articles are inserted here.

create table if not exists public.admins (
  id bigint generated by default as identity primary key,
  email text not null,
  password_hash text not null,
  name text default 'Editor',
  created_at timestamptz not null default now()
);

create unique index if not exists admins_email_lower_idx
  on public.admins (lower(email));

-- RLS with NO policies: this table is completely locked away from the
-- public keys. Only the backend (which uses the secret/service key and
-- bypasses RLS) can read or write it. Password hashes never leave the server.
alter table public.admins enable row level security;

